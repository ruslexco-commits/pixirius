'use strict';

// Грязь (просьба пользователя): сыпучая земля, которая растворяется в воде,
// оседает на твёрдых пикселях и снова смывается водой.
//
// Растворение — как у чёрных солей (просьба: "систему замешивания грязи в
// воде как с чёрными солями"): грязь — в среде растворов
// (IS_SOLUTION_MEDIUM), и соседние клетки меняются с ней долями обычным
// перемешиванием (mixParts) — брошенная в воду грязь расходится мутью.
// Вода с долями грязи — мутный раствор (setComposition: жидкого больше —
// SOLUTION, цвет — среднее долей), клетка, где грязи не меньше воды, —
// сыпучая грязь.
//
// Отличие от солей — оседание на пикселях (mudStick): мутная вода у
// твёрдого или сыпучего пикселя (не из среды растворов) откладывает на него
// долю грязи — у пикселя растёт поле dirt (MUD_DIRT_PER_PART за долю, едет с
// частицей, рисуется к цвету грязи), а в воде доля грязи становится водой.
// С тем же шансом — обратно: вода у испачканного пикселя забирает с него
// долю грязи, одна её доля воды становится грязью. "С таким же успехом" —
// на каждую долю: доля грязи в воде оседает на соседний пиксель с шансом
// MUD_STICK_CHANCE, доля на пикселе вымывается с тем же шансом. Поэтому в
// мутной воде пиксели пачкаются, пока грязи на них не станет примерно
// столько же, сколько в воде рядом, а в чистой — отмываются. Грязь при
// этом никуда не девается: доли в воде плюс dirt / MUD_DIRT_PER_PART на
// пикселях постоянны. (Первая проба выбирала направление по случайной доле
// воды — грязь или вода, — и в мутной воде, где воды девять долей из
// десяти, пиксель отмывался вдевятеро чаще, чем пачкался.)
//
// Сыпучие растворы (просьба пользователя): грязь, земля и чёрные соли
// (IS_POWDER_MIX) смешиваются долями друг с другом, но, в отличие от
// жидкостей и газов, не сами собой, а только при движении — сдвинувшаяся
// частица (упала, скатилась) с шансом POWDER_MIX_CHANCE меняется одной
// долей с сыпучим под собой, а нет его — с соседним сбоку (powderMix).
// Тип клетки — по долям (setComposition): чего твёрдого больше, тем и
// будет; цвет — средний (грязь — своим правилом, см. solColor).
//
// История: первая версия растворяла грязь своими шансами (в стоячей воде
// медленно, в текущей быстро), опускала муть вниз и копила у дна осадком, а
// пачкание было отдельным, без переноса грязи. Пользователь попросил как у
// солей, с оседанием на пикселях.
//
// Методы класса Sim, вынесенные в отдельный файл: класс ниже — только
// контейнер, extendSim переносит его методы в Sim.prototype (см. core.js).

// Шанс в кадр на каждую долю: доле грязи в воде — осесть на соседний
// пиксель, доле на пикселе — вымыться в воду (один шанс на оба направления).
const MUD_STICK_CHANCE = 0.03;
// Сколько единиц dirt (0..255) — одна доля грязи на пикселе: до 10 долей.
const MUD_DIRT_PER_PART = 25;
// Шанс, что сдвинувшаяся сыпучая частица смешается долей с соседом.
const POWDER_MIX_CHANCE = 0.5;

class SimMud {
  // Сыпучая грязь — как чёрные соли: обычная жизнь долей (перемешивание с
  // водой, кипение воды в мокрой грязи).
  reactMud(x, y, i) {
    this.reactSolutionLike(x, y, i);
  }

  // Сыпучее в клетке j только что сдвинулось: смешаться долей с сыпучим
  // под ним, а нет его — со случайным соседом сбоку (см. шапку).
  powderMix(j) {
    if (Math.random() >= POWDER_MIX_CHANCE) return;
    const w = this.w, x = j % w, type = this.type;
    let ni = j + w;
    if (ni >= type.length || IS_POWDER_MIX[type[ni]] !== 1) {
      ni = Math.random() < 0.5 ? (x > 0 ? j - 1 : -1) : (x < w - 1 ? j + 1 : -1);
      if (ni < 0 || IS_POWDER_MIX[type[ni]] !== 1) return;
    }
    const a = this.comp(j), b = this.comp(ni);
    if (a === b && a < 1024) return;   // одно и то же чистое вещество
    const pa = this.randomMatterPart(a), pb = this.randomMatterPart(b);
    if (pa < 0 || pb < 0 || pa === pb) return;
    const a2 = solMove(a, pa, pb), b2 = solMove(b, pb, pa);
    if (a2 === a || b2 === b) return;
    this.setComposition(j, a2);
    this.setComposition(ni, b2);
  }

  // Можно ли отложить грязь на пиксель вида t: твёрдое или сыпучее, кроме
  // среды растворов (сама грязь, чёрные соли — с ними грязь мешается долями).
  dirtable(t) {
    // У живых dirt — урон (sim/human.js, HIT_DAMAGE).
    if (IS_SOLUTION_MEDIUM[t] === 1 || t === EL.HUMAN || t === EL.PROTAGONIST || t === EL.COLONIST) return false;
    const el = ELEMENTS[t];
    return !!el && (el.cat === CAT.SOLID || el.cat === CAT.POWDER);
  }

  // Испачкан ли кто-то из четырёх соседей клетки i (дёшево, без бросков:
  // чистая вода у чистых пикселей ничего не тратит).
  dirtyNear(x, y, i) {
    const w = this.w, d = this.dirt;
    return (x < w - 1 && d[i + 1] !== 0) || (x > 0 && d[i - 1] !== 0) || (y < this.h - 1 && d[i + w] !== 0) || (y > 0 && d[i - w] !== 0);
  }

  // Вода в i и случайный соседний пиксель: отложить долю грязи или забрать
  // её (см. шапку).
  mudStick(x, y, i) {
    const k = (Math.random() * 4) | 0;
    const nx = x + DX4[k], ny = y + DY4[k];
    if (!this.inBounds(nx, ny)) return;
    const ni = ny * this.w + nx;
    if (!this.dirtable(this.type[ni])) return;
    const c = this.comp(i), dirt = this.dirt;
    const inWater = solGet(c, EL.MUD), onPixel = (dirt[ni] / MUD_DIRT_PER_PART) | 0;
    const r = Math.random();
    let c2 = c;
    if (r < MUD_STICK_CHANCE * inWater) {
      if (dirt[ni] > 255 - MUD_DIRT_PER_PART) return;
      c2 = solMove(c, EL.MUD, P_WATER);
      if (c2 === c) return;
      dirt[ni] += MUD_DIRT_PER_PART;
    } else if (r < MUD_STICK_CHANCE * (inWater + onPixel)) {
      // Забирает грязь только вода: у клетки без доли воды (реагент, кислота)
      // solMove не убрал бы воду, а грязь добавил бы — долей выходило 11.
      if (dirt[ni] < MUD_DIRT_PER_PART || solGet(c, P_WATER) === 0) return;
      c2 = solMove(c, P_WATER, EL.MUD);
      if (c2 === c) return;
      dirt[ni] -= MUD_DIRT_PER_PART;
    } else return;
    this.setComposition(i, c2);
    this.markDirty(ni);
  }
}

extendSim(SimMud);
