'use strict';

// Рабочий поток параллельной симуляции (см. sim/threads.js), браузерная
// сторона. Сам по себе скрипт ничего не знает о симуляции: первое сообщение
// от main.js приносит адреса скриптов (те же, что грузит страница, до
// рендера — таблицы элементов и sim/*.js), и общую память мира. Скрипты
// обычные, не модули: importScripts выполняет их в общей глобальной области
// потока ровно как теги на странице, и extendSim собирает тот же Sim.
//
// Дальше поток навсегда уходит в threadWorkerLoop: сообщений он больше не
// читает, общается с главным только через общую память. Останавливается
// флагом stopThreads или terminate() со стороны страницы.

self.onmessage = (e) => {
  const { scripts, init } = e.data;
  importScripts(...scripts);
  const sim = new Sim(init.w, init.h);
  attachSharedArrays(sim, init);
  threadWorkerLoop(sim);
};
