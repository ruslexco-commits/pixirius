'use strict';

// Нагрузка на твёрдые пиксели: сколько веса через каждый из них передаётся
// вниз, к опоре, и в какую сторону он при этом давит. Первый шаг к "более
// реалистичной физике" (просьба пользователя: вмятины, и чтобы материал мог
// проседать, когда под ним ничего нет). Пока только считается и показывается
// (клавиша 4, отладочный вид) — ход мира она не меняет, поэтому
// tools/compare.js по-прежнему обязан выдавать OK.
//
// Идея пользователя. "В момент изменения структуры берётся каждый пиксель и
// его масса, и по телу распространяется волна (не визуально, а как механика)
// с порядком обхода соседей — слева направо, сверху вниз:
//     5 4 5
//     3 0 3
//     2 1 2
// где 0 — место волны, цифры — очерёдность, в которой она пробует идти
// дальше. Упёрлась в тупик — идёт обратно, ушла за край карты — исчезает
// (у неподвижного тела она всегда находит путь к опоре). Каждый блок помнит
// прошедшую через него силу и сумму векторов направлений. Больше стойкости
// (умноженной на число, при котором пиксель держит около 50 себе подобных) —
// пиксель перегружен".
//
// Как это посчитано. Волна, которая от каждого пикселя идёт по одному и тому
// же порядку обхода, из любой точки приходит по одному и тому же пути: пути
// сливаются в дерево, корни которого — опоры (нижний край поля и пиксели,
// прижатые к якорям: стена, пустота, клонер). Поэтому вместо отдельной
// волны на каждый пиксель (а это сотни шагов на пиксель при каждой правке
// постройки) считается само дерево, один проход по полю:
//  1. поиск в ширину от опор по твёрдым пикселям с устойчивостью больше нуля
//     (соседи — все восемь; по диагонали — только если рядом по стороне есть
//     твёрдое, иначе волна протискивалась бы в угол стыка двух тел);
//     глубина d — число шагов до опоры, она и гарантирует отсутствие тупиков
//     и кругов: "вернуться из тупика" волна уже не нужна;
//  2. родитель пикселя — сосед с меньшей глубиной, которого волна пробует
//     раньше всех по очерёдности выше (вниз, потом по диагонали вниз, в
//     стороны, вверх, по диагонали вверх); в паре равных (лево/право)
//     выбор по чётности x+y — одинаковый у всех копий мира;
//  3. от самых глубоких к опорам: нагрузка пикселя (его масса плюс всё,
//     что пришло от детей) уходит родителю, а вектор давления родителя
//     пополняется нагрузкой ребёнка, умноженной на направление от ребёнка к
//     родителю. Собственный вес — вектор вниз. Итог: куда пиксель давят.
//
// Поля нагрузки не двигаются с частицей — как stability, они принадлежат
// месту и пересчитываются при смене скелета (structureChanged, по нему же
// _stabRecomputed). Мелочь вроде песка или воды скелет не меняет, так что
// пересчёт идёт редко, а не каждый кадр. Без балок: второй слой пока в
// нагрузке не участвует.
//
// Методы класса Sim, вынесенные в отдельный файл: класс ниже — только
// контейнер, extendSim переносит его методы в Sim.prototype (см. core.js).

// Сколько веса выдерживает пиксель на единицу стойкости. Стойкость камня 4 и
// масса 0.14: 4 * 1.75 = 7 = 50 камней друг на друге; у железа 5 * 1.75 =
// 8.75 при массе 0.2 — 44 пикселя, у стали 56, у дерева 70. Берётся именно
// стойкость (по просьбе: "стойкость на что-то помножить"), а не масса, чтобы
// у сплава и ржавчины, у которых стойкость считается по долям, нагрузка
// следовала за ней.
const LOAD_PER_TOUGHNESS = 1.75;

// Очерёдность соседей волны (см. шапку): вниз, вниз-влево, вниз-вправо,
// влево, вправо, вверх, вверх-влево, вверх-вправо. Пары 1-2, 3-4 и 6-7
// равноправны — внутри пары порядок зависит от чётности клетки.
const LOAD_DX = [0, -1, 1, -1, 1, 0, -1, 1];
const LOAD_DY = [1, 1, 1, 0, 0, -1, -1, -1];

class SimLoad {
  initLoad() {
    const n = this.w * this.h;
    this.load = new Float32Array(n);
    this.loadFX = new Float32Array(n);
    this.loadFY = new Float32Array(n);
    this._loadDist = new Int32Array(n);
    this._loadQ = new Int32Array(n);
  }

  // Предел пикселя i: нагрузка, больше которой он перегружен. Для якоря и
  // не-твёрдого — бесконечность (якорь держит сколько угодно).
  loadCap(i) {
    const t = this.type[i];
    if (IS_STRUCTURAL[t] !== 1) return Infinity;
    return this.cellToughness(i, t) * LOAD_PER_TOUGHNESS;
  }

  // Раз в кадр после computeStability: пересчёт только если скелет сменился.
  updateLoad() {
    if (!this._stabRecomputed) return;
    this.computeLoad();
  }

  computeLoad() {
    const w = this.w, h = this.h, n = w * h;
    const type = this.type, stab = this.stability, crushed = this.crushed;
    const load = this.load, fx = this.loadFX, fy = this.loadFY;
    const dist = this._loadDist, q = this._loadQ;
    load.fill(0); fx.fill(0); fy.fill(0);
    // Узлы волны: твёрдое, которое держится (продавленное тоже: опору оно
    // передаёт, см. computeStability). -1 — узел ещё не достигнут, -2 — не
    // узел.
    let tail = 0;
    for (let i = 0; i < n; i++) {
      if (IS_STRUCTURAL[type[i]] === 1 && (stab[i] > 0 || crushed[i] !== 0)) {
        dist[i] = -1;
        load[i] = type[i] === EL.ALLOY ? this.alloyMass(i) : PIXEL_MASS[type[i]];
        fy[i] = load[i];   // собственный вес давит вниз
      } else dist[i] = -2;
    }
    // Опоры: нижний край поля и клетки, прижатые к якорю.
    for (let i = 0; i < n; i++) {
      if (dist[i] !== -1) continue;
      const x = i % w, y = (i / w) | 0;
      if (y === h - 1
          || (x > 0 && IS_ANCHOR[type[i - 1]] === 1) || (x < w - 1 && IS_ANCHOR[type[i + 1]] === 1)
          || (y > 0 && IS_ANCHOR[type[i - w]] === 1) || IS_ANCHOR[type[i + w]] === 1) {
        dist[i] = 0;
        q[tail++] = i;
      }
    }
    // Поиск в ширину: глубина до опоры.
    for (let head = 0; head < tail; head++) {
      const i = q[head];
      const x = i % w, y = (i / w) | 0, d = dist[i] + 1;
      for (let k = 0; k < 8; k++) {
        const nx = x + LOAD_DX[k], ny = y + LOAD_DY[k];
        if (nx < 0 || nx >= w || ny < 0 || ny >= h) continue;
        const j = ny * w + nx;
        if (dist[j] !== -1) continue;
        if (LOAD_DX[k] !== 0 && LOAD_DY[k] !== 0 && dist[y * w + nx] === -2 && dist[ny * w + x] === -2) continue;
        dist[j] = d;
        q[tail++] = j;
      }
    }
    // Нагрузка от самых глубоких к опорам: каждый отдаёт всё родителю.
    for (let head = tail - 1; head >= 0; head--) {
      const i = q[head];
      const d = dist[i];
      if (d === 0) continue;
      const x = i % w, y = (i / w) | 0;
      const flip = ((x + y) & 1) === 1;
      let p = -1, pdx = 0, pdy = 0;
      for (let k = 0; k < 8 && p < 0; k++) {
        // Внутри пары равных (индексы 1-2, 3-4, 6-7) порядок меняется на
        // нечётных клетках.
        const kk = flip && (k === 1 || k === 3 || k === 6) ? k + 1 : flip && (k === 2 || k === 4 || k === 7) ? k - 1 : k;
        const dx = LOAD_DX[kk], dy = LOAD_DY[kk];
        const nx = x + dx, ny = y + dy;
        if (nx < 0 || nx >= w || ny < 0 || ny >= h) continue;
        const j = ny * w + nx;
        if (dist[j] < 0 || dist[j] >= d) continue;
        if (dx !== 0 && dy !== 0 && dist[y * w + nx] === -2 && dist[ny * w + x] === -2) continue;
        p = j; pdx = dx; pdy = dy;
      }
      if (p < 0) continue;
      const l = load[i];
      load[p] += l;
      fx[p] += l * pdx;
      fy[p] += l * pdy;
    }
  }
}

extendSim(SimLoad);
