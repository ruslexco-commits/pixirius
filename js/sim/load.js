'use strict';

// Нагрузка на твёрдые пиксели: сколько веса через каждый из них передаётся
// вниз, к опоре, и в какую сторону он при этом давит (просьба пользователя:
// "более реалистичная физика" — вмятины, и чтобы материал мог проседать, когда
// под ним ничего нет). Считается и показывается (клавиша 4, отладочный вид), а
// перегруженный пиксель ещё и сдвигается (loadYield, см. ниже).
//
// Идея пользователя. "В момент изменения структуры берётся каждый пиксель и
// его масса, и по телу распространяется волна (не визуально, а как механика)
// с порядком обхода соседей — слева направо, сверху вниз:
//     5 4 5
//     3 0 3
//     2 1 2
// где 0 — место волны, цифры — очерёдность, в которой она пробует идти
// дальше. Упёрлась в тупик — идёт обратно, ушла за край карты — исчезает
// (у неподвижного тела она всегда находит путь к опоре). Каждый блок помнит
// прошедшую через него силу и сумму векторов направлений. Больше стойкости
// (умноженной на число, при котором пиксель держит около 50 себе подобных) —
// пиксель перегружен".
//
// Как это посчитано. Волна, которая от каждого пикселя идёт по одному и тому
// же порядку обхода, из любой точки приходит по одному и тому же пути: пути
// сливаются в дерево, корни которого — опоры (нижний край поля и пиксели,
// прижатые к якорям: стена, пустота, клонер). Поэтому вместо отдельной
// волны на каждый пиксель (а это сотни шагов на пиксель при каждой правке
// постройки) считается само дерево, один проход по полю:
//  1. поиск в ширину от опор по твёрдым пикселям с устойчивостью больше нуля
//     (соседи — все восемь; по диагонали — только если рядом по стороне есть
//     твёрдое, иначе волна протискивалась бы в угол стыка двух тел);
//     глубина d — число шагов до опоры, она и гарантирует отсутствие тупиков
//     и кругов: "вернуться из тупика" волна уже не нужна;
//  2. родитель пикселя — сосед с меньшей глубиной, которого волна пробует
//     раньше всех по очерёдности выше (вниз, потом по диагонали вниз, в
//     стороны, вверх, по диагонали вверх); в паре равных (лево/право)
//     выбор по чётности x+y — одинаковый у всех копий мира;
//  3. от самых глубоких к опорам: нагрузка пикселя (его масса плюс всё,
//     что пришло от детей) уходит родителю, а вектор давления родителя
//     пополняется нагрузкой ребёнка, умноженной на направление от ребёнка к
//     родителю. Собственный вес — вектор вниз. Итог: куда пиксель давят.
//
// Поля нагрузки не двигаются с частицей — как stability, они принадлежат
// месту и пересчитываются при смене скелета (structureChanged, по нему же
// _stabRecomputed). Мелочь вроде песка или воды скелет не меняет, так что
// пересчёт идёт редко, а не каждый кадр.
// Балки (второй слой) в нагрузке участвуют: клетка с балкой без твёрдого — узел с
// материалом балки (stabId), несёт вес, но двигаться не может и перегруженная
// осыпается своим материалом (dropBeam).
//
// Методы класса Sim, вынесенные в отдельный файл: класс ниже — только
// контейнер, extendSim переносит его методы в Sim.prototype (см. core.js).

// Сколько веса выдерживает пиксель на единицу стойкости. Стойкость камня 4 и
// масса 0.14: 4 * 1.75 = 7 = 50 камней друг на друге; у железа 5 * 1.75 =
// 8.75 при массе 0.2 — 44 пикселя, у стали 56, у дерева 70. Берётся именно
// стойкость (по просьбе: "стойкость на что-то помножить"), а не масса, чтобы
// у сплава и ржавчины, у которых стойкость считается по долям, нагрузка
// следовала за ней.
const LOAD_PER_TOUGHNESS = 1.75;

// Очерёдность соседей волны (см. шапку): вниз, вниз-влево, вниз-вправо,
// влево, вправо, вверх, вверх-влево, вверх-вправо. Пары 1-2, 3-4 и 6-7
// равноправны — внутри пары порядок зависит от чётности клетки.
const LOAD_DX = [0, -1, 1, -1, 1, 0, -1, 1];
const LOAD_DY = [1, 1, 1, 0, 0, -1, -1, -1];

// ---- перегрузка: пиксель уступает ----
//
// Пиксель, у которого нагрузка больше предела, сдвигается туда, куда его давят
// (вектор давления: сумма нагрузок детей по направлениям и собственный вес
// вниз, поэтому нависающий пиксель проседает, хоть пути волны идут вбок). Из
// направлений берутся ближайшие по углу к вектору — само направление, соседние
// по 45 градусов и сидящие почти поперёк (так пережатый перешеек выдавливает
// пиксели вбок, а не стоит вечно). Если там занято другим твёрдым — вместо
// сдвига идёт передача силы: сосед получает избыток (нагрузка минус предел) и
// сдвигается сам, если с ним нагрузка выше его предела; сдвинулся — освободил
// место, и пиксель идёт следом. Не сдвинулся — ничего не происходит: упирающийся
// в опору столб (низ башни) остаётся стоять.
// Пиксели позади сдвинувшегося (в обратную сторону, по прямой) тянутся за ним:
// просьба пользователя — "все пиксели в полярном направлении относительно
// направления его движения подвинутся тоже".
//
// Работает только в кадре, где скелет сменился и нагрузка пересчитана: сдвиг
// сам меняет скелет, и деформация идёт цепочкой кадров, а не разом. Шанс в
// кадр (LOAD_YIELD_RATE на долю перегрузки: на 20 процентов выше предела — 1% в
// кадр, вдвое — 5%, в десять раз — каждый кадр) размазывает её по времени.
// Включается полем sim.loadYieldOn (по умолчанию нет, в игре — клавиша 5).
const LOAD_YIELD_RATE = 0.05;
// Пиксель уступает, только когда нагрузка не меньше стольких пределов. Предел
// "50 себе подобных" — это про разрушение, а у обычной постройки (башня выше 50
// пикселей на сплошном основании, толстый пол) он превышен десятки раз вдоль
// всей опоры; без этого порога карта "Вышка" за 600 кадров перестраивалась на
// 15 тысяч клеток и кадр дорожал в шесть раз. Вмятины и проседание — это
// нагрузка в разы выше предела (острый выступ, перешеек, длинный вылет).
const LOAD_YIELD_MIN_RATIO = 3;
// Сколько сдвигов за кадр, не больше: каждый сменяет скелет и стоит пересчёта.
const LOAD_YIELD_MAX_PER_FRAME = 64;
// Сколько пикселей позади сдвинувшегося следуют за ним.
const LOAD_TRAIL_MAX = 512;
// Глубина цепочки передачи силы.
const LOAD_PUSH_DEPTH = 12;
// Восемь направлений: вправо, влево, вниз, вверх и диагонали; INV — 1/длина.
const YDX = [1, -1, 0, 0, 1, 1, -1, -1];
const YDY = [0, 0, 1, -1, 1, -1, 1, -1];
const YINV = [1, 1, 1, 1, Math.SQRT1_2, Math.SQRT1_2, Math.SQRT1_2, Math.SQRT1_2];

class SimLoad {
  initLoad() {
    const n = this.w * this.h;
    this.load = new Float32Array(n);
    this.loadFX = new Float32Array(n);
    this.loadFY = new Float32Array(n);
    this._loadDist = new Int32Array(n);
    this._loadQ = new Int32Array(n);
    this._loadN = 0;
    // Сдвиги под нагрузкой (клавиша 5 в игре). По умолчанию выключены: на карте
    // "Вышка" они перестраивают нижние постройки и удорожают кадр в 4-5 раз,
    // пока это не решено — включает игрок. loadWanted — вид нагрузки (клавиша
    // 4) просит считать её и без сдвигов; ставит отрисовка.
    this.loadYieldOn = false;
    this.loadWanted = false;
    this._loadFresh = false;
  }

  // Предел пикселя i: нагрузка, больше которой он перегружен. Для якоря и
  // не-твёрдого — бесконечность (якорь держит сколько угодно).
  loadCap(i) {
    // Несущий материал клетки с учётом второго слоя: твёрдое, а если его нет —
    // материал балки (stabId): балка несёт вес и сама может быть перегружена.
    const id = this.stabId(i);
    if (IS_STRUCTURAL[id] !== 1) return Infinity;
    return this.cellToughness(i, id) * LOAD_PER_TOUGHNESS;
  }

  // Раз в кадр после computeStability: пересчёт только если скелет сменился.
  updateLoad() {
    // Ничего не нужно — ничего не считаем (и при следующем включении
    // посчитаем заново: скелет мог поменяться, пока было выключено).
    if (!this.loadYieldOn && !this.loadWanted) { this._loadFresh = false; return; }
    if (!this._stabRecomputed && this._loadFresh) return;
    this._loadFresh = true;
    this.computeLoad();
    if (!this.loadYieldOn) return;
    const q = this._loadQ, load = this.load, fx = this.loadFX, fy = this.loadFY, moved = this.moved;
    let done = 0;
    for (let k = 0; k < this._loadN; k++) {
      const i = q[k];
      if (moved[i]) continue;
      const cap = this.loadCap(i);
      const over = load[i] - cap;
      if (over <= 0 || load[i] < LOAD_YIELD_MIN_RATIO * cap) continue;
      // Балка (в клетке нет твёрдого) двигаться не может — второй слой стоит на
      // месте, — поэтому перегруженная ломается: осыпается своим материалом
      // (как балка без опоры, dropBeam), и дальше это обычное твёрдое, которое
      // уступает нагрузке, как любое другое.
      const beamOnly = IS_STRUCTURAL[this.type[i]] !== 1;
      if (!beamOnly && !this.loadCanMove(i)) continue;
      // Шанс растёт с перегрузкой: чуть выше предела — ползучесть, на порядок
      // выше — перешеек лопается сразу.
      if (Math.random() >= LOAD_YIELD_RATE * over / cap) continue;
      if (beamOnly) {
        if (this.beam[i] === 0) continue;
        if (this.type[i] === EL.EMPTY) this.dropBeam(i); else this.removeBeam(i);
        moved[i] = 1;
        if (++done >= LOAD_YIELD_MAX_PER_FRAME) break;
        continue;
      }
      if (this.loadYield(i, fx[i], fy[i], over, 0) && ++done >= LOAD_YIELD_MAX_PER_FRAME) break;
    }
  }

  // Свежая устойчивость и нагрузка вне шага: между шагами (и на паузе) мир
  // перерисовывают кистью, а пересчёт идёт только в step() — вид нагрузки и
  // лупа показывали бы данные до правки (жалоба пользователя: "вся стойкость
  // должна обновляться на карте, чтобы я видел свежие данные"). Пересчёт
  // безопасен (случайных чисел не тратит, зависит только от скелета): шаг
  // после него получит то же и сам пропустит. needLoad=false — нужна только
  // устойчивость (вид на клавише 1).
  refreshLoad(needLoad = true) {
    const was = this._stabRecomputed;
    this._stabRecomputed = false;
    this.computeStability();
    const changed = this._stabRecomputed;
    this._stabRecomputed = was || changed;
    if (needLoad && (changed || !this._loadFresh)) { this.computeLoad(); this._loadFresh = true; }
  }

  // Двигаемое под нагрузкой твёрдое: не якорь и не застывшее масло (у него
  // направление связи в extra, при сдвиге оно бы врало).
  loadCanMove(i) {
    const t = this.type[i];
    return IS_STRUCTURAL[t] === 1 && t !== EL.OILFILM;
  }

  // Куда пиксель может уйти: пустота, газ, жидкость, огонь — и не клетка
  // балки (твёрдое сквозь неё не проходит, как у rollBody).
  loadPassable(j) {
    const t = this.type[j];
    return (t === EL.EMPTY || IS_LIQUID[t] === 1 || IS_GASLIKE[t] === 1 || t === EL.FIRE) && this.beam[j] === 0;
  }

  // Пиксель i, на который давит вектор (vx, vy) с избытком over над его
  // пределом, пробует сдвинуться. true — сдвинулся (клетка i теперь другая).
  loadYield(i, vx, vy, over, depth) {
    const w = this.w, h = this.h;
    const x = i % w, y = (i / w) | 0;
    const len = Math.sqrt(vx * vx + vy * vy);
    if (len === 0) return false;
    let used = 0;
    for (let n = 0; n < 5; n++) {
      let best = -1, bd = -Infinity;
      for (let k = 0; k < 8; k++) {
        if ((used >> k) & 1) continue;
        const d = (vx * YDX[k] + vy * YDY[k]) * YINV[k];
        if (d > bd) { bd = d; best = k; }
      }
      if (best < 0 || bd < -0.3 * len) break;
      used |= 1 << best;
      const dx = YDX[best], dy = YDY[best];
      // Вверх пиксель не выдавливает, пока давление само не смотрит вверх: иначе
      // сжатый бок выпускал бы столбики выше тела (хвост тянул бы за ним целый
      // столб).
      if (dy < 0 && vy >= 0) continue;
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || nx >= w || ny < 0 || ny >= h) continue;
      // По диагонали — не сквозь угол стыка двух твёрдых.
      if (dx !== 0 && dy !== 0 && !this.loadPassable(y * w + nx) && !this.loadPassable(ny * w + x)) continue;
      const j = ny * w + nx;
      if (!this.loadPassable(j)) {
        // Занято твёрдым — передача силы: оно должно уступить само. Только по
        // самому направлению давления (n === 0): ветвление по всем пяти шло бы
        // экспоненциально (первая версия висела по две секунды на кадр).
        if (n > 0 || depth >= LOAD_PUSH_DEPTH || this.moved[j] || !this.loadCanMove(j)) continue;
        const pushed = this.load[j] + over - this.loadCap(j);
        if (pushed <= 0) continue;
        if (!this.loadYield(j, dx, dy, pushed, depth + 1)) continue;
        if (!this.loadPassable(j)) continue;
      }
      this.loadMove(i, j, dx, dy);
      return true;
    }
    return false;
  }

  // Сдвиг пикселя i в j (по направлению dx, dy) и подтягивание хвоста: пиксели
  // позади по прямой (не больше LOAD_TRAIL_MAX) занимают освободившееся место.
  loadMove(i, j, dx, dy) {
    const w = this.w, h = this.h, stab = this.stability, moved = this.moved;
    this.swapFields(i, j);
    // Устойчивость — по месту (как в rollBody): иначе в обходе этого кадра
    // сдвинувшийся пиксель на новом месте с нулём рассыпался бы.
    let t = stab[i]; stab[i] = stab[j]; stab[j] = t;
    moved[j] = 1;
    let x = i % w, y = (i / w) | 0;
    let nxt = i;
    for (let k = 1; k <= LOAD_TRAIL_MAX; k++) {
      const cx = x - k * dx, cy = y - k * dy;
      if (cx < 0 || cx >= w || cy < 0 || cy >= h) break;
      const c = cy * w + cx;
      if (moved[c] || !this.loadCanMove(c)) break;
      this.swapFields(c, nxt);
      t = stab[c]; stab[c] = stab[nxt]; stab[nxt] = t;
      moved[nxt] = 1;
      nxt = c;
    }
  }

  computeLoad() {
    const w = this.w, h = this.h, n = w * h;
    const type = this.type, stab = this.stability, crushed = this.crushed;
    const load = this.load, fx = this.loadFX, fy = this.loadFY;
    const dist = this._loadDist, q = this._loadQ;
    load.fill(0); fx.fill(0); fy.fill(0);
    // Узлы волны: твёрдое, которое держится (продавленное тоже: опору оно
    // передаёт, см. computeStability), и клетка с балкой, в которой твёрдого
    // нет, — так же, как это читает устойчивость (stabId): балка несёт вес
    // своим материалом. -1 — узел ещё не достигнут, -2 — не узел.
    const beam = this.beam;
    let tail = 0;
    for (let i = 0; i < n; i++) {
      const t = type[i];
      const sid = (IS_STRUCTURAL[t] === 1 || IS_ANCHOR[t] === 1) ? t : beam[i];
      if (IS_STRUCTURAL[sid] === 1 && (stab[i] > 0 || crushed[i] !== 0)) {
        dist[i] = -1;
        load[i] = t === EL.ALLOY ? this.alloyMass(i) : PIXEL_MASS[sid];
        fy[i] = load[i];   // собственный вес давит вниз
      } else dist[i] = -2;
    }
    // Опоры: нижний край поля и клетки, прижатые к якорю.
    for (let i = 0; i < n; i++) {
      if (dist[i] !== -1) continue;
      const x = i % w, y = (i / w) | 0;
      if (y === h - 1
          || (x > 0 && IS_ANCHOR[type[i - 1]] === 1) || (x < w - 1 && IS_ANCHOR[type[i + 1]] === 1)
          || (y > 0 && IS_ANCHOR[type[i - w]] === 1) || IS_ANCHOR[type[i + w]] === 1) {
        dist[i] = 0;
        q[tail++] = i;
      }
    }
    // Поиск в ширину: глубина до опоры.
    for (let head = 0; head < tail; head++) {
      const i = q[head];
      const x = i % w, y = (i / w) | 0, d = dist[i] + 1;
      for (let k = 0; k < 8; k++) {
        const nx = x + LOAD_DX[k], ny = y + LOAD_DY[k];
        if (nx < 0 || nx >= w || ny < 0 || ny >= h) continue;
        const j = ny * w + nx;
        if (dist[j] !== -1) continue;
        if (LOAD_DX[k] !== 0 && LOAD_DY[k] !== 0 && dist[y * w + nx] === -2 && dist[ny * w + x] === -2) continue;
        dist[j] = d;
        q[tail++] = j;
      }
    }
    this._loadN = tail;
    // Нагрузка от самых глубоких к опорам: каждый отдаёт всё родителю.
    for (let head = tail - 1; head >= 0; head--) {
      const i = q[head];
      const d = dist[i];
      if (d === 0) continue;
      const x = i % w, y = (i / w) | 0;
      const flip = ((x + y) & 1) === 1;
      let p = -1, pdx = 0, pdy = 0;
      for (let k = 0; k < 8 && p < 0; k++) {
        // Внутри пары равных (индексы 1-2, 3-4, 6-7) порядок меняется на
        // нечётных клетках.
        const kk = flip && (k === 1 || k === 3 || k === 6) ? k + 1 : flip && (k === 2 || k === 4 || k === 7) ? k - 1 : k;
        const dx = LOAD_DX[kk], dy = LOAD_DY[kk];
        const nx = x + dx, ny = y + dy;
        if (nx < 0 || nx >= w || ny < 0 || ny >= h) continue;
        const j = ny * w + nx;
        if (dist[j] < 0 || dist[j] >= d) continue;
        if (dx !== 0 && dy !== 0 && dist[y * w + nx] === -2 && dist[ny * w + x] === -2) continue;
        p = j; pdx = dx; pdy = dy;
      }
      if (p < 0) continue;
      const l = load[i];
      load[p] += l;
      fx[p] += l * pdx;
      fy[p] += l * pdy;
    }
  }
}

extendSim(SimLoad);
